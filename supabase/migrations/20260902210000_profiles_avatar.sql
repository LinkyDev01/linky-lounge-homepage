-- ============================================================================
-- 0014 · 회원 프로필 사진 (profiles.avatar_url)
-- ============================================================================
-- 운영자 2026-09-02: "수집할 수 있는건 최대한 할거야. 프로필사진도 있으면 좋지.
-- 장기적으론 결국 필요해. 커뮤니티 될 거니까."
--
-- **왜 지금 컬럼을 만드는가** — 카카오·구글 동의 화면에서 '프로필 사진'을 받기로
-- 했는데, 담을 자리가 없으면 **받아서 버리는 항목**이 된다. 개인정보처리방침에
-- 수집 항목으로 적으면서 실제로는 저장하지 않으면 고지가 사실과 어긋난다 —
-- 2026-09-01 에 결제 페이지의 이메일 칸을 지운 것이 정확히 그 반대 사고였다
-- (수집하지 않는 항목을 수집한다고 고지하고 있었다). 그래서 **방침 개정과 같은 PR**에서
-- 저장 자리를 만든다.
--
-- 이 파일이 지키는 결정:
--   1. **URL 만 담는다.** 이미지 파일을 우리 쪽에 복사하지 않는다 — 소셜 CDN 의 주소를
--      그대로 들고 있다가 화면이 참조한다. 파일을 받아 두면 보관·파기 대상이 하나 더
--      늘고(스토리지), 소셜에서 사진을 바꿔도 우리 사본은 옛것으로 남는다.
--   2. **파기 함수는 무변경.** `profiles` 의 PK 는 `auth.users.id` **cascade** 라
--      탈퇴하면 행이 통째로 사라진다(0011 결정) — `applications` 처럼 '행을 남기고
--      비우는' 규율이 필요 없다. CLAUDE.md §4 의 "개인정보 컬럼을 추가하면 파기 함수
--      2종도 같은 PR 에서" 규율은 그 두 함수가 다루는 `applications`·`customer_activities`
--      에 대한 것이고, 이 표는 애초에 그 함수들의 대상이 아니다.
--   3. **RLS 는 이미 전면 거부** — 새 정책을 만들지 않는다(0011 과 같은 판단).
--
-- ⚠ 사진 URL 도 개인정보다(누구인지 식별하는 이미지를 가리킨다). 회원이 탈퇴하면
--   cascade 로 함께 사라지는 것을 0011 스모크에서 이미 실증했다.
-- ============================================================================

alter table public.profiles
  add column if not exists avatar_url text;

comment on column public.profiles.avatar_url is
  '소셜 계정의 프로필 사진 URL (파일이 아니라 주소만 — 결정 1). 로그인할 때마다 소셜 값과 맞춘다. 탈퇴 시 cascade 로 행과 함께 사라진다';
